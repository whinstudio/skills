#!/usr/bin/env bash
# Post-generate setup: git init + an initial commit, unless the project is already a repository.
# The Unity .gitignore (Library/, Temp/, Builds/, …) comes with the template; none is added here.
# Usage: setup.sh <projectDir>
set -euo pipefail

DIR="${1:?project dir required}"
[ -d "$DIR" ] || { echo "FAIL: $DIR is not a directory"; exit 1; }
cd "$DIR"

if ! command -v git >/dev/null 2>&1; then
  echo "SKIP: git not found; install git, then run: git init && git add -A && git commit -m 'Initial commit'"
  exit 0
fi
if [ -e .git ]; then
  echo "OK: git (already a repository, left as is)"
  exit 0
fi

git init -q -b develop
git add -A
NAME="$(git config user.name 2>/dev/null || echo cmpose)"
EMAIL="$(git config user.email 2>/dev/null || echo noreply@example.com)"
git -c user.name="$NAME" -c user.email="$EMAIL" commit -q -m "Initial commit (generated by cmpose)"
echo "OK: git (initialized, initial commit)"
